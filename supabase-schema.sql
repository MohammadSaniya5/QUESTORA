-- QUESTORA Supabase PostgreSQL schema
-- Run this entire file in Supabase Dashboard -> SQL Editor.
CREATE TABLE IF NOT EXISTS public.profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('student','admin')),
  email TEXT NOT NULL UNIQUE,
  hall_ticket TEXT UNIQUE,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  phone TEXT,
  address TEXT,
  password_hash TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_text TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('QUANT','EAMCET')),
  subject TEXT NOT NULL CHECK (subject IN ('ARITHMETIC','MATHEMATICS','PHYSICS','CHEMISTRY')),
  difficulty TEXT NOT NULL DEFAULT 'MEDIUM' CHECK (difficulty IN ('EASY','MEDIUM','HARD')),
  option_a TEXT NOT NULL,
  option_b TEXT NOT NULL,
  option_c TEXT NOT NULL,
  option_d TEXT NOT NULL,
  correct_option SMALLINT NOT NULL CHECK (correct_option BETWEEN 0 AND 3),
  explanation TEXT,
  marks INTEGER NOT NULL DEFAULT 1 CHECK (marks > 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_archived BOOLEAN NOT NULL DEFAULT FALSE,
  created_at BIGINT NOT NULL DEFAULT (extract(epoch from now()) * 1000)::bigint
);

CREATE TABLE IF NOT EXISTS public.exam_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES public.profiles(id) ON DELETE CASCADE,
  started_at BIGINT NOT NULL,
  ends_at BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS','SUBMITTED','TIME_EXPIRED')),
  submitted BIGINT,
  score INTEGER,
  coins INTEGER,
  best_streak INTEGER DEFAULT 0,
  current_index INTEGER DEFAULT 0,
  last_activity BIGINT
);

CREATE TABLE IF NOT EXISTS public.attempt_questions (
  attempt_id BIGINT NOT NULL REFERENCES public.exam_attempts(id) ON DELETE CASCADE,
  question_id BIGINT NOT NULL REFERENCES public.questions(id),
  position INTEGER NOT NULL,
  PRIMARY KEY (attempt_id, question_id),
  UNIQUE (attempt_id, position)
);

CREATE TABLE IF NOT EXISTS public.attempt_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id BIGINT NOT NULL,
  question_id BIGINT NOT NULL,
  chosen SMALLINT CHECK (chosen BETWEEN 0 AND 3),
  is_correct BOOLEAN NOT NULL,
  answered_at BIGINT NOT NULL,
  UNIQUE (attempt_id, question_id),
  FOREIGN KEY (attempt_id, question_id) REFERENCES public.attempt_questions(attempt_id, question_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.app_config (
  key TEXT PRIMARY KEY,
  value INTEGER NOT NULL CHECK (value >= 0)
);

CREATE INDEX IF NOT EXISTS idx_questions_selection ON public.questions(category, subject, is_active, is_archived);
CREATE INDEX IF NOT EXISTS idx_attempt_status_ends ON public.exam_attempts(status, ends_at);
CREATE INDEX IF NOT EXISTS idx_attempt_questions_attempt_position ON public.attempt_questions(attempt_id, position);
CREATE INDEX IF NOT EXISTS idx_attempt_answers_attempt ON public.attempt_answers(attempt_id, answered_at);

